"""بيولّد lib/l10n/ar_digits.dart: نسخة من ترجمة العربي بتحوّل أي رقم في الجمل لأرقام عربي (٠١٢٣…).
شغّله بعد أي تعديل في ملفات الـ arb:  python3 tools/gen_ar_digits.py   (و --check في الـ CI)."""
import json, sys
from collections import OrderedDict

EN = json.load(open('lib/l10n/app_en.arb'), object_pairs_hook=OrderedDict)
OUT = 'lib/l10n/ar_digits.dart'
# جمل فيها أرقام لازم تفضل زي ما هي (رقم النسخة، كود الدعوة/الخطأ، رسالة فيها لينك، كلام كتبه المستخدم).
KEEP = {'appVersion', 'updateAvailableBody', 'errorCode', 'inviteMessage', 'chatYouPrefix'}
DART_TYPES = {'int': 'int', 'num': 'num', 'double': 'double', 'String': 'String', 'DateTime': 'DateTime', 'Object': 'Object'}

lines = [
    '// GENERATED by tools/gen_ar_digits.py — متعدلش فيه بإيدك.',
    '// ignore_for_file: type=lint',
    "import 'package:flutter/widgets.dart';",
    '',
    "import 'digits.dart';",
    "import 'gen/app_localizations.dart';",
    '',
    '/// ترجمة العربي بأرقام عربي في كل الجمل.',
    'class ArDigitsLocalizations extends AppLocalizations {',
    '  ArDigitsLocalizations(this._b) : super(_b.localeName);',
    '  final AppLocalizations _b;',
    '',
]
for key, val in EN.items():
    if key.startswith('@'):
        continue
    meta = EN.get('@' + key, {})
    ph = meta.get('placeholders', {}) if isinstance(meta, dict) else {}
    if not ph:
        lines.append(f'  @override\n  String get {key} => _b.{key};')
        continue
    params = ', '.join(f"{DART_TYPES.get(m.get('type', 'Object'), 'Object')} {n}" for n, m in ph.items())
    args = ', '.join(ph.keys())
    call = f'_b.{key}({args})'
    body = call if key in KEEP else f'arDigits({call})'
    lines.append(f'  @override\n  String {key}({params}) => {body};')
lines += [
    '}',
    '',
    '/// بيستخدم الترجمة العادية، وفي العربي بيلفّها بالأرقام العربي.',
    'class LocalizedDigitsDelegate extends LocalizationsDelegate<AppLocalizations> {',
    '  const LocalizedDigitsDelegate();',
    '',
    '  @override',
    '  bool isSupported(Locale locale) => AppLocalizations.delegate.isSupported(locale);',
    '',
    '  @override',
    '  Future<AppLocalizations> load(Locale locale) async => wrapDigits(await AppLocalizations.delegate.load(locale));',
    '',
    '  @override',
    '  bool shouldReload(LocalizedDigitsDelegate old) => false;',
    '}',
    '',
    'AppLocalizations wrapDigits(AppLocalizations t) => t.localeName.startsWith(\'ar\') ? ArDigitsLocalizations(t) : t;',
    '',
    '/// زي lookupAppLocalizations (للإشعارات والويدجت) بس بالأرقام العربي.',
    'AppLocalizations lookupLocalized(Locale locale) => wrapDigits(lookupAppLocalizations(locale));',
    '',
]
text = '\n'.join(lines)
if '--check' in sys.argv:
    if open(OUT).read() != text:
        sys.exit('lib/l10n/ar_digits.dart مش متحدّث: شغّل python3 tools/gen_ar_digits.py')
    print('ar_digits.dart up to date')
else:
    open(OUT, 'w').write(text)
    print('wrote', OUT)
